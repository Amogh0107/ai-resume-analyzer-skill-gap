def generate_learning_roadmap(missing_skills):
    roadmap = []

    for skill in missing_skills:
        if skill in LEARNING_DATABASE:
            data = LEARNING_DATABASE[skill]

            roadmap.append({
                "skill": skill,
                "level": data["level"],
                "duration": data["duration"],
                "priority": data["priority"],
                "platform": data["platform"],
                "resource": data["resource"],
                "youtube": data["youtube"],
                "practice": data.get("practice", "Not Available"),
                "paid_course": data.get("paid_course", "Free Resources Available"),
                "description": data["description"]
            })

    return roadmap